  const btnQuickCompleteActive = document.getElementById('btnQuickCompleteActive');
  const nextTaskName = document.getElementById('nextTaskName');
  const nextTaskTime = document.getElementById('nextTaskTime');

  let currentActiveTaskId = null;

  function updateRealTimeClock() {
    const now = new Date();
    const hours = String(now.getHours()).padStart(2, '0');
    const mins = String(now.getMinutes()).padStart(2, '0');
    const secs = String(now.getSeconds()).padStart(2, '0');
    liveClockDisplay.textContent = `${hours}:${mins}:${secs}`;
    
    // Check banner state every minute or clock tick
    updateActiveTaskBanner(now);
  }

  function updateActiveTaskBanner(nowDate) {
    const nowHoursMins = `${String(nowDate.getHours()).padStart(2, '0')}:${String(nowDate.getMinutes()).padStart(2, '0')}`;
    const todayStr = getTodayStr();

    // Filter tasks for today
    const todayTasks = state.dailyTasks.filter(t => t.date === todayStr);

    let currentTask = null;
    let nextTask = null;

    // Sort today's tasks by timeStart
    todayTasks.sort((a, b) => a.timeStart.localeCompare(b.timeStart));

    for (let task of todayTasks) {
      if (nowHoursMins >= task.timeStart && nowHoursMins <= task.timeEnd) {
        currentTask = task;
      } else if (nowHoursMins < task.timeStart && (!nextTask || task.timeStart < nextTask.timeStart)) {
        nextTask = task;
      }
    }

    if (currentTask) {
      currentActiveTaskId = currentTask.id;
      activeTaskName.textContent = currentTask.taskName;
      activeTaskCategory.innerHTML = `<i class="fa-solid fa-tag"></i> ${currentTask.category}`;
      activeTaskTime.querySelector('span').textContent = `${currentTask.timeStart} - ${currentTask.timeEnd}`;
      
      activeTaskStatusTag.className = 'banner-status-tag active-now';
      activeTaskStatusTag.innerHTML = `<i class="fa-solid fa-play-circle"></i> Sedang Berlangsung (${currentTask.status})`;
      
      btnQuickCompleteActive.style.display = currentTask.status === 'Done' ? 'none' : 'inline-flex';
    } else {
      currentActiveTaskId = null;
      activeTaskName.textContent = 'Tidak Ada Tugas Aktif Saat Ini';
      activeTaskCategory.innerHTML = `<i class="fa-solid fa-clock"></i> Istirahat / Free Time`;
      activeTaskTime.querySelector('span').textContent = `--:-- - --:--`;
      
      activeTaskStatusTag.className = 'banner-status-tag';
      activeTaskStatusTag.innerHTML = `<i class="fa-solid fa-mug-hot"></i> Idle`;
      btnQuickCompleteActive.style.display = 'none';
    }

    if (nextTask) {
      nextTaskName.textContent = nextTask.taskName;
      nextTaskTime.textContent = `(${nextTask.timeStart} - ${nextTask.timeEnd})`;
    } else {
      nextTaskName.textContent = 'Tidak ada tugas berikutnya hari ini';
      nextTaskTime.textContent = '';
    }
  }

