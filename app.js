  // Push Data (Upload to Google Sheets)
  async function pushToGoogleSheets() {
    const url = state.settings.gasUrl || gasWebAppUrl.value.trim();
    if (!url) {
      showToast('Harap masukkan Web App URL Google Apps Script di menu Settings!', 'error');
      switchTab('sync-settings');
      return;
    }

    btnPushToGas.disabled = true;
    btnPushToGas.innerHTML = `<i class="fa-solid fa-spinner fa-spin"></i> Uploading...`;

    try {
      const payload = {
        action: 'push',
        timestamp: new Date().toISOString(),
        state: state
      };

      // Send via POST JSON
      const res = await fetch(url, {
        method: 'POST',
        headers: { 'Content-Type': 'text/plain;charset=utf-8' }, // Avoid CORS preflight issues with Apps Script
        body: JSON.stringify(payload)
      });

      const json = await res.json();
      if (json.status === 'success') {
        const timeNow = new Date().toLocaleTimeString('id-ID');
        state.settings.lastSynced = timeNow;
        saveState();
        gasSyncDetails.textContent = `Data berhasil di-upload ke Google Sheets pada ${timeNow}.`;
        showToast('🎉 Data berhasil di-upload (Push) ke Google Sheets!', 'success');
      } else {
        throw new Error(json.message || 'Respons server gagal');
      }
    } catch (e) {
      console.error('GAS Push Error:', e);
      gasSyncDetails.textContent = `Gagal upload: ${e.message}`;
      showToast(`Gagal Upload: ${e.message}. Pastikan URL Web App benar dan di-deploy sebagai "Anyone".`, 'error');
    } finally {
      btnPushToGas.disabled = false;
      btnPushToGas.innerHTML = `<i class="fa-solid fa-cloud-arrow-up"></i> Upload Data (Push)`;
    }
  }

  // Pull Data (Download from Google Sheets)
  async function pullFromGoogleSheets() {
    const url = state.settings.gasUrl || gasWebAppUrl.value.trim();
    if (!url) {
      showToast('Harap masukkan Web App URL Google Apps Script di menu Settings!', 'error');
      switchTab('sync-settings');
      return;
    }

    btnPullFromGas.disabled = true;
    btnPullFromGas.innerHTML = `<i class="fa-solid fa-spinner fa-spin"></i> Downloading...`;

    try {
      const fetchUrl = url + (url.includes('?') ? '&' : '?') + 'action=pull&t=' + Date.now();
      const res = await fetch(fetchUrl);
      const json = await res.json();

      if (json.status === 'success' && json.state) {
        state = { ...defaultState, ...json.state, settings: { ...state.settings } };
        const timeNow = new Date().toLocaleTimeString('id-ID');
        state.settings.lastSynced = timeNow;
        saveState();
        renderAllModules();
        gasSyncDetails.textContent = `Data berhasil di-download dari Google Sheets pada ${timeNow}.`;
        showToast('⚡ Data berhasil di-download (Pull) dari Google Sheets!', 'success');
      } else {
        throw new Error(json.message || 'Format data Google Sheets tidak valid');
      }
    } catch (e) {
      console.error('GAS Pull Error:', e);
      gasSyncDetails.textContent = `Gagal download: ${e.message}`;
      showToast(`Gagal Download: ${e.message}`, 'error');
    } finally {
      btnPullFromGas.disabled = false;
      btnPullFromGas.innerHTML = `<i class="fa-solid fa-cloud-arrow-down"></i> Download Data (Pull)`;
    }
  }

